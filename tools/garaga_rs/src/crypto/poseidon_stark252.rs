use crate::definitions::{FieldElement, Stark252PrimeField};

pub(crate) struct PoseidonCairoStark252;

#[allow(clippy::op_ref)]
impl PoseidonCairoStark252 {
    pub(crate) fn hades_permutation(state: &mut [FieldElement<Stark252PrimeField>; 3]) {
        let mut index = 0;
        for _ in 0..4 {
            Self::full_round(state, index);
            index += 3;
        }
        for _ in 0..83 {
            Self::partial_round(state, index);
            index += 1;
        }
        for _ in 0..4 {
            Self::full_round(state, index);
            index += 3;
        }
    }

    #[inline]
    fn full_round(state: &mut [FieldElement<Stark252PrimeField>; 3], index: usize) {
        for (i, value) in state.iter_mut().enumerate() {
            *value = &(*value) + &ROUND_CONSTANTS[index + i];
            *value = &(*value).square() * &*value;
        }
        Self::mix(state);
    }

    #[inline]
    fn partial_round(state: &mut [FieldElement<Stark252PrimeField>; 3], index: usize) {
        state[2] = &state[2] + &ROUND_CONSTANTS[index];
        state[2] = &state[2].square() * &state[2];
        Self::mix(state);
    }

    #[inline(always)]
    fn mix(state: &mut [FieldElement<Stark252PrimeField>; 3]) {
        let t = &state[0] + &state[1] + &state[2];
        state[0] = &t + &state[0].double();
        state[1] = &t - &state[1].double();
        state[2] = &t - (&state[2] + &state[2] + &state[2]);
    }
}

