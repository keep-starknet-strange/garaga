"""Measure the same Honk verification path in Cairo steps and Sierra gas."""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

CONTRACT = "src/contracts/autogenerated/noir_ultra_keccak_zk_honk_example"
TEST = "test_verify_ultra_keccak_zk_honk_proof"


def run(command, cwd):
    result = subprocess.run(command, cwd=cwd, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f"{command}:\n{result.stdout}\n{result.stderr}")
    return result.stdout + result.stderr


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo", type=Path, default=Path(__file__).resolve().parents[1]
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--named-profile",
        action="store_true",
        help="Build readable profiles in a copy and require identical CASM bytecode",
    )
    args = parser.parse_args()
    repo = args.repo.resolve()
    project = repo / CONTRACT
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    artifacts = output.parent / output.stem
    artifacts.mkdir(exist_ok=True)
    versions = {
        tool: run([tool, "--version"], project).strip()
        for tool in ("scarb", "snforge", "cairo-profiler")
    }
    (artifacts / "build.log").write_text(run(["scarb", "build"], project))
    modes = {}
    for mode in ("cairo-steps", "sierra-gas"):
        command = [
            "snforge",
            "test",
            TEST,
            "--detailed-resources",
            "--tracked-resource",
            mode,
        ]
        if mode == "cairo-steps":
            command.append("--save-trace-data")
        log = run(command, project)
        assert "Tests: 1 passed, 0 failed" in log, log
        (artifacts / f"{mode}.log").write_text(log)
        name = "steps" if mode == "cairo-steps" else "sierra gas"
        value = re.search(rf"^\s*{name}: (\d+)\s*$", log, re.MULTILINE)
        assert value, log
        modes[mode] = {"resource": int(value[1]), "command": command}

    # Build the profile from the steps trace. Measure gas in a separate run.
    traces = list((project / "snfoundry_trace").glob(f"*{TEST}.json"))
    assert len(traces) == 1, traces
    profile = artifacts / "profile.pb.gz"
    run(
        [
            "cairo-profiler",
            "build-profile",
            str(traces[0]),
            "--output-path",
            str(profile),
        ],
        project,
    )
    # A cairo-steps trace does not contain Sierra gas samples.
    for sample in ("steps", "range check96 builtin", "mul mod builtin"):
        report = run(
            [
                "cairo-profiler",
                "view",
                str(profile),
                "--sample",
                sample,
                "--limit",
                "30",
            ],
            project,
        )
        (artifacts / f"profile-{sample.replace(' ', '-')}.txt").write_text(report)

    target = project / "target/dev"
    prefix = "noir_ultra_keccak_zk_honk_example_UltraKeccakZKHonkVerifier"
    casm_path = target / f"{prefix}.compiled_contract_class.json"
    sierra_path = target / f"{prefix}.contract_class.json"
    casm = json.loads(casm_path.read_text())
    sierra = json.loads(sierra_path.read_text())
    source_hashes = {
        str(path.relative_to(repo)): hashlib.sha256(path.read_bytes()).hexdigest()
        for directory in (project / "src", project / "tests")
        for path in sorted(directory.rglob("*"))
        if path.is_file()
    }
    for path in (
        project / "Scarb.toml",
        repo / "Scarb.toml",
        repo / "src/Scarb.toml",
        repo / "src/corelib_imports/Scarb.toml",
    ):
        if path.is_file():
            source_hashes[str(path.relative_to(repo))] = hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
    result = {
        "revision": run(["git", "rev-parse", "HEAD"], repo).strip(),
        "versions": versions,
        "contract": CONTRACT,
        "test": TEST,
        "scope": "Foundry library-dispatch test, including ECIP and test harness; no live fee estimate",
        "modes": modes,
        "sizes": {
            "casm_felts": len(casm["bytecode"]),
            "sierra_felts": len(sierra["sierra_program"]),
            "casm_json_bytes": casm_path.stat().st_size,
            "sierra_json_bytes": sierra_path.stat().st_size,
        },
        "source_sha256": source_hashes,
        "noir_versions": json.loads((repo / "tools/make/constants.json").read_text())[
            "noir"
        ],
    }
    examples = repo / "hydra/garaga/starknet/honk_contract_generator/examples"
    vk = (examples / "vk_ultra_keccak.bin").read_bytes()
    proof = (examples / "proof_ultra_keccak_zk.bin").read_bytes()
    result["case"] = {
        "log_n": int.from_bytes(vk[:32], "big"),
        "public_inputs_size": int.from_bytes(vk[32:64], "big"),
        "proof_bytes": len(proof),
        "vk_sha256": hashlib.sha256(vk).hexdigest(),
        "proof_sha256": hashlib.sha256(proof).hexdigest(),
    }
    digest = hashlib.sha256()
    for directory in (repo / "src/src", repo / "src/corelib_imports/src"):
        for path in sorted(directory.rglob("*.cairo")):
            digest.update(str(path.relative_to(repo)).encode())
            digest.update(path.read_bytes())
    result["cairo_library_sha256"] = digest.hexdigest()
    if args.named_profile:
        with tempfile.TemporaryDirectory(prefix="garaga-noir-profile-") as temporary:
            copied = Path(temporary)
            shutil.copytree(
                repo / "src",
                copied / "src",
                ignore=shutil.ignore_patterns(
                    "target", "snfoundry_trace", ".snfoundry_cache"
                ),
            )
            shutil.copy(repo / "README.md", copied / "README.md")
            named_project = copied / CONTRACT
            manifest = named_project / "Scarb.toml"
            manifest.write_text(
                manifest.read_text().replace(
                    "sierra-replace-ids = false", "sierra-replace-ids = true"
                )
            )
            run(["scarb", "build"], named_project)
            named_casm = json.loads(
                (named_project / "target/dev" / casm_path.name).read_text()
            )
            assert (
                named_casm["bytecode"] == casm["bytecode"]
            ), "Debug names changed CASM; do not compare these profiles"
            log = run(
                [
                    "snforge",
                    "test",
                    TEST,
                    "--tracked-resource",
                    "cairo-steps",
                    "--detailed-resources",
                    "--save-trace-data",
                ],
                named_project,
            )
            assert re.search(r"^\s*steps: (\d+)\s*$", log, re.MULTILINE)[1] == str(
                modes["cairo-steps"]["resource"]
            )
            traces = list((named_project / "snfoundry_trace").glob(f"*{TEST}.json"))
            assert len(traces) == 1
            named_profile = artifacts / "named-profile.pb.gz"
            run(
                [
                    "cairo-profiler",
                    "build-profile",
                    str(traces[0]),
                    "--output-path",
                    str(named_profile),
                ],
                named_project,
            )
            (artifacts / "named-profile-steps.txt").write_text(
                run(
                    [
                        "cairo-profiler",
                        "view",
                        str(named_profile),
                        "--sample",
                        "steps",
                        "--limit",
                        "40",
                    ],
                    named_project,
                )
            )
            result["named_profile"] = {"identical_casm": True, "identical_steps": True}
    output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"modes": modes, "sizes": result["sizes"]}, indent=2))


if __name__ == "__main__":
    main()
