"""Measure Ed25519 VM steps and actual Sierra gas in separate Foundry runs."""

import argparse
import hashlib
import io
import json
import re
import subprocess
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = "9b327b4ab3e1e2535df689765adb88b99762f739"
PROOF_SYSTEMS = {
    "groth16_example_bn254": "test_verify_groth16_proof_bn254",
    "groth16_example_bls12_381": "test_verify_groth16_proof_bls12_381",
    "risc0_verifier_bn254": "test_verify_r0_groth16_proof_bn254",
    "sp1_verifier_bn254": "test_verify_sp1_groth16_proof_bn254",
}


def command(arguments, cwd):
    return subprocess.run(
        arguments, cwd=cwd, capture_output=True, text=True, check=True
    ).stdout


def measure(repo, test_filter, output, label, package="garaga", location="src"):
    measurements = {}
    for resource, unit in [("cairo-steps", "steps"), ("sierra-gas", "sierra gas")]:
        print(f"{label}: {test_filter}, {resource}", flush=True)
        result = subprocess.run(
            [
                "snforge",
                "test",
                "-p",
                package,
                test_filter,
                "--tracked-resource",
                resource,
                "--detailed-resources",
            ],
            cwd=repo / location,
            capture_output=True,
            text=True,
        )
        log = output.parent / f"{output.stem}-{label}-{resource}.log"
        log.write_text(result.stdout + result.stderr)
        if result.returncode:
            raise RuntimeError(f"Foundry failed: {log}")
        matches = re.findall(
            r"\[PASS\] (\S+) [^\n]*\n\s+" + unit + r": (\d+)", result.stdout
        )
        if not matches:
            raise RuntimeError(f"No {unit} measurements found in {log}")
        for name, value in matches:
            measurements.setdefault(name.rsplit("::", 1)[-1], {})[
                unit.replace(" ", "_")
            ] = int(value)
    if any(set(value) != {"steps", "sierra_gas"} for value in measurements.values()):
        raise RuntimeError("Different tests ran under the two resource modes")
    return measurements


def proof_systems(repo, output, label):
    result = {}
    for package, test_filter in PROOF_SYSTEMS.items():
        location = f"src/contracts/autogenerated/{package}"
        values = measure(
            repo, test_filter, output, f"{label}-{package}", package, location
        )
        if set(values) != {test_filter}:
            raise RuntimeError(f"Unexpected proof test selection: {package}")
        # Foundry builds test targets. Build the deployable artifact separately.
        command(["scarb", "build", "-p", package], repo / location)
        artifacts = list(
            (repo / location / "target/dev").glob(
                f"{package}_*.compiled_contract_class.json"
            )
        )
        if len(artifacts) != 1:
            raise RuntimeError(f"Expected one compiled verifier: {package}")
        casm = json.loads(artifacts[0].read_text())
        sierra = json.loads(
            artifacts[0]
            .with_name(
                artifacts[0].name.replace(
                    ".compiled_contract_class.json", ".contract_class.json"
                )
            )
            .read_text()
        )
        result[package] = {
            **values[test_filter],
            "casm_felts": len(casm["bytecode"]),
            "sierra_felts": len(sierra["sierra_program"]),
        }
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", default=BASELINE)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    revision = command(["git", "rev-parse", args.baseline], ROOT).strip()
    current = command(["git", "rev-parse", "HEAD"], ROOT).strip()
    source_paths = [
        "src/src/ec/ed25519.cairo",
        "src/src/ec/ec_ops.cairo",
        "src/src/ec/pairing/groth16.cairo",
        "src/src/signatures/eddsa_25519.cairo",
        "src/src/circuits/ed25519.cairo",
        "src/src/tests/ed25519_subgroup_tests.cairo",
        "src/Scarb.toml",
        "src/src/definitions/curves.cairo",
        "hydra/garaga/ed25519.py",
        "hydra/garaga/precompiled_circuits/compilable_circuits/ed25519.py",
        "tools/make/constants.json",
        "tools/divide_and_pair/vectors.py",
        "tools/divide_and_pair/generate.py",
        "tools/divide_and_pair/benchmark.py",
    ]
    hashes = {
        path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
        for path in source_paths
    }
    archive = subprocess.run(
        ["git", "archive", revision], cwd=ROOT, capture_output=True, check=True
    ).stdout
    with tempfile.TemporaryDirectory(prefix="garaga-ed25519-baseline-") as temporary:
        baseline = Path(temporary)
        with tarfile.open(fileobj=io.BytesIO(archive)) as contents:
            contents.extractall(baseline, filter="data")
        before = measure(baseline, "test_eddsa", output, "signature-before")
        proofs_before = proof_systems(baseline, output, "proof-before")
    after = measure(ROOT, "test_eddsa", output, "signature-after")
    if len(before) != 3 or set(before) != set(after):
        raise RuntimeError("Expected the same three active EdDSA regression tests")
    subgroup = measure(ROOT, "test_ed25519_benchmark", output, "subgroup")
    if len(subgroup) != 8:
        raise RuntimeError(
            "Expected four generic and four divide-and-pair measurements"
        )
    proofs_after = proof_systems(ROOT, output, "proof-after")
    for path, expected in hashes.items():
        if hashlib.sha256((ROOT / path).read_bytes()).hexdigest() != expected:
            raise RuntimeError(f"Source changed during the benchmark: {path}")
    payload = {
        "baseline_revision": revision,
        "revision": current,
        "source_dirty": bool(command(["git", "status", "--porcelain"], ROOT).strip()),
        "source_sha256": hashes,
        "scarb": command(["scarb", "--version"], ROOT).strip(),
        "snforge": command(["snforge", "--version"], ROOT).strip(),
        "signature_before": before,
        "signature_after": after,
        "subgroup": subgroup,
        "proof_systems_before": proofs_before,
        "proof_systems_after": proofs_after,
        "notes": [
            "Steps and Sierra gas come from separate resource modes.",
            "The baseline Cairo Ed25519 subgroup API was unimplemented.",
            "The generic subgroup comparison is an added full-integer oracle on identical inputs.",
            "Sierra gas excludes transaction fees and calldata costs.",
        ],
    }
    output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(f"Wrote {output}", flush=True)


if __name__ == "__main__":
    main()
