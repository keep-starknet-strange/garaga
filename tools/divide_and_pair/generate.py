"""Generate Cairo vectors from independent complete Edwards group arithmetic."""

import argparse
from pathlib import Path

from garaga.hints.io import int_to_u384
from tools.divide_and_pair.vectors import P, vectors, weierstrass

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src/src/tests/ed25519_subgroup_tests.cairo"


def render():
    source = """// Generated by tools/divide_and_pair/generate.py.
use core::circuit::u384;
use core::num::traits::Zero;
use garaga::definitions::{G1Point, get_n};
use garaga::ec::ec_ops::{G1PointTrait, ec_safe_add};
use garaga::ec::ed25519::{is_in_prime_order_subgroup, is_small_order_edwards};
use garaga::signatures::eddsa_25519::{
    EdDSASignature, EdDSASignatureWithHint, is_valid_eddsa_signature,
};

// This oracle uses the full integer ell and no subgroup-dependent GLV hints.
fn generic_membership(point: G1Point) -> bool {
    let mut scalar = get_n(4);
    let mut base = point;
    let mut result: G1Point = Zero::zero();
    while scalar != 0 {
        if scalar % 2 == 1 { result = ec_safe_add(result, base, 4); }
        base = ec_safe_add(base, base, 4);
        scalar /= 2;
    }
    result.is_infinity()
}
"""
    for index, (scalar, coset, (x, y)) in enumerate(vectors()):
        subgroup = str(coset == 0).lower()
        small = str(scalar == 0).lower()
        point = weierstrass((x, y)).to_cairo_1()
        source += f"""
#[test]
fn test_ed25519_subgroup_coset_{index}() {{
    let point = {point};
    assert!(is_in_prime_order_subgroup(point) == {subgroup});
    assert!(is_small_order_edwards({int_to_u384(x)}, {int_to_u384(y)}) == {small});
}}
"""
        if scalar == 0:
            compressed = y + (x % 2) * 2**255
            # No MSM witness is needed: these inputs must fail before the MSM.
            for side in ["R", "A"]:
                base_x, base_y = vectors()[8][2]
                base_compressed = base_y + (base_x % 2) * 2**255
                r, a, rx, ax = (
                    (compressed, base_compressed, x, base_x)
                    if side == "R"
                    else (base_compressed, compressed, base_x, x)
                )
                source += f"""
#[test]
fn test_ed25519_reject_torsion_{side}_{index}() {{
    let signature = EdDSASignatureWithHint {{
        signature: EdDSASignature {{Ry_twisted: {r}, s: 1, msg: array![].span()}},
        msm_hint: array![].span(), sqrt_Rx_hint: {rx}, sqrt_Px_hint: {ax},
    }};
    assert!(!is_valid_eddsa_signature(signature, {a}));
}}
"""
        if index in [8, 9, 10, 16]:
            label = {8: "prime", 9: "mixed_odd", 10: "mixed_even", 16: "prime_nqr"}[
                index
            ]
            source += f"""
#[test]
fn test_ed25519_benchmark_generic_{label}() {{
    assert!(generic_membership({point}) == {subgroup});
}}

#[test]
fn test_ed25519_benchmark_divide_pair_{label}() {{
    assert!(is_in_prime_order_subgroup({point}) == {subgroup});
}}
"""
    source += f"""
#[test]
fn test_ed25519_subgroup_trait() {{
    let point = {weierstrass(vectors()[8][2]).to_cairo_1()};
    point.assert_in_subgroup_excluding_infinity(4);
}}

#[test]
#[should_panic]
fn test_ed25519_subgroup_trait_reject_mixed() {{
    let point = {weierstrass(vectors()[9][2]).to_cairo_1()};
    point.assert_in_subgroup_excluding_infinity(4);
}}
"""
    base = weierstrass(vectors()[8][2])
    for label, x, y in [
        ("x", base.x + P, base.y),
        ("y", base.x, base.y + P),
        ("wide", 2**300, base.y),
        ("off_curve", 1, 1),
    ]:
        source += f"""
#[test]
fn test_ed25519_reject_noncanonical_{label}() {{
    let point = G1Point {{x: {int_to_u384(x)}, y: {int_to_u384(y)}}};
    assert!(!is_in_prime_order_subgroup(point));
}}
"""
    base_x, base_y = vectors()[8][2]
    base_compressed = base_y + (base_x % 2) * 2**255
    for y in [P, P + 1, P + 18]:
        source += f"""
#[test]
fn test_ed25519_reject_noncanonical_encoding_{y-P}() {{
    let signature = EdDSASignatureWithHint {{
        signature: EdDSASignature {{Ry_twisted: {base_compressed}, s: 1, msg: array![].span()}},
        msm_hint: array![].span(), sqrt_Rx_hint: {base_x}, sqrt_Px_hint: 0,
    }};
    assert!(!is_valid_eddsa_signature(signature, {y}));
}}
"""
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Use the same formatter as the generated circuits.
    import subprocess
    import tempfile

    with tempfile.TemporaryDirectory(dir=TARGET.parent) as temporary:
        path = Path(temporary) / "vectors.cairo"
        path.write_text(render())
        subprocess.run(
            ["scarb", "fmt", str(path)],
            cwd=ROOT / "src",
            check=True,
            capture_output=True,
        )
        source = path.read_text()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            raise SystemExit(
                "Stale Ed25519 vectors: run tools/divide_and_pair/generate.py"
            )
    else:
        TARGET.write_text(source)


if __name__ == "__main__":
    main()
