import copy
import hashlib
import json
import re
import tomllib
from pathlib import Path

import pytest

from garaga.curves import CURVES, CurveID
from garaga.starknet import constants
from garaga.starknet.groth16_contract_generator.calldata import (
    groth16_calldata_from_vk_and_proof,
)
from garaga.starknet.groth16_contract_generator.parsing_utils import (
    Groth16Proof,
    Groth16VerifyingKey,
)

ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "hydra/garaga/starknet/groth16_contract_generator/examples"
FIXTURE = json.loads((EXAMPLES / "proof_sp1.json").read_text())
RELEASE = json.loads((ROOT / "tools/make/constants.json").read_text())["sp1"]


def test_stored_receipt_matches_its_source_fingerprints():
    source = json.loads((EXAMPLES / "sp1_artifacts.json").read_text())["fixture_source"]
    assert (
        hashlib.sha256(bytes.fromhex(FIXTURE["proof"][2:])).hexdigest()
        == source["proof_sha256"]
    )
    assert (
        hashlib.sha256(bytes.fromhex(FIXTURE["publicValues"][2:])).hexdigest()
        == source["public_values_sha256"]
    )


def test_sdk_lock_and_generated_parameters_match_the_release():
    manifest = tomllib.loads((ROOT / "tools/sp1_verifier/Cargo.toml").read_text())
    sdk = manifest["dev-dependencies"]["sp1-verifier"]
    assert sdk["version"] == "=" + RELEASE["sdk_version"]
    lock = tomllib.loads((ROOT / "tools/sp1_verifier/Cargo.lock").read_text())
    assert (
        next(p["version"] for p in lock["package"] if p["name"] == "sp1-verifier")
        == RELEASE["sdk_version"]
    )
    assert constants.SP1_SDK_VERSION == RELEASE["sdk_version"]
    assert constants.SP1_VERIFIER_VERSION == RELEASE["verifier_version"]
    assert constants.SP1_VERIFIER_HASH.hex() == RELEASE["verifier_hash"][2:]
    assert constants.SP1_VK_ROOT == int(RELEASE["vk_root"], 16)


def test_v6_receipt_calldata_and_cairo_artifacts_are_coherent():
    proof = Groth16Proof.from_dict(FIXTURE)
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_sp1.json")
    assert len(vk.ic) == 6
    assert len(proof.public_inputs) == 5
    assert proof.public_inputs[2] == 0
    assert proof.public_inputs[3] == constants.SP1_VK_ROOT
    python = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=False)
    rust = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=True)
    assert python == rust
    for relative in [
        "src/contracts/autogenerated/sp1_verifier_bn254/tests/proof_calldata.txt",
        "src/src/tests/proof_calldata.txt",
    ]:
        stored = [int(word, 0) for word in (ROOT / relative).read_text().split()]
        assert stored == python[1:], "Stale SP1 calldata. Run make rewrite."
    cairo = (ROOT / "src/src/apps/sp1_constants.cairo").read_text()
    assert re.search(r"N_PUBLIC_INPUTS: usize = 5;", cairo)
    root = re.search(r"SP1_VK_ROOT: u256 = (0x[0-9a-f]+);", cairo)
    assert root and int(root[1], 16) == constants.SP1_VK_ROOT


@pytest.mark.parametrize(
    "kind",
    ["selector", "exit_code", "vk_root", "nonce_range", "truncated", "extra", "legacy"],
)
def test_parser_rejects_incompatible_sp1_receipts(kind):
    data = copy.deepcopy(FIXTURE)
    raw = bytearray.fromhex(data["proof"][2:])
    if kind == "selector":
        raw[0] ^= 1
    elif kind == "exit_code":
        raw[35] = 1
    elif kind == "vk_root":
        raw[67] ^= 1
    elif kind == "nonce_range":
        raw[68:100] = CURVES[CurveID.BN254.value].n.to_bytes(32, "big")
    elif kind == "truncated":
        raw = raw[:-1]
    elif kind == "extra":
        raw += b"x"
    else:
        raw = bytes.fromhex("a4594c59") + raw[100:]
    data["proof"] = "0x" + raw.hex()
    with pytest.raises((ValueError, AssertionError)):
        Groth16Proof.from_dict(data)


@pytest.mark.parametrize("kind", ["nonce", "program", "public_values"])
def test_groth16_equation_binds_sp1_metadata(kind):
    data = copy.deepcopy(FIXTURE)
    key = {"nonce": "proof", "program": "vkey", "public_values": "publicValues"}[kind]
    raw = bytearray.fromhex(data[key][2:])
    raw[99 if kind == "nonce" else -1] ^= 1
    data[key] = "0x" + raw.hex()
    proof = Groth16Proof.from_dict(data)
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_sp1.json")
    with pytest.raises(Exception):
        groth16_calldata_from_vk_and_proof(vk, proof, use_rust=False)
