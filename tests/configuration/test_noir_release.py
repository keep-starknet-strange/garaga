"""Keep Noir sources, SDK pins, proof bundles, and generated calldata consistent."""

import hashlib
import json
import random
from pathlib import Path

import pytest

from garaga import garaga_rs
from garaga.curves import CURVES, CurveID
from garaga.precompiled_circuits.zk_honk import (
    HonkVk,
    Wire,
    ZKHonkProof,
    ZKHonkVerifierCircuits,
)
from garaga.starknet.constants import BB_VERSION, NARGO_VERSION
from garaga.starknet.honk_contract_generator.calldata import (
    get_ultra_flavor_honk_calldata_from_vk_and_proof,
)

ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "hydra/garaga/starknet/honk_contract_generator/examples"
MANIFEST = json.loads((EXAMPLES / "noir_artifacts.json").read_text())


def bundle(case):
    files = MANIFEST["cases"][case]["files"]
    return {
        name: (EXAMPLES / data["path"]).read_bytes() for name, data in files.items()
    }


def test_noir_sdk_pins():
    pins = json.loads((ROOT / "tools/make/constants.json").read_text())["noir"]
    toolchain = MANIFEST["toolchain"]
    assert toolchain["bb_version"] == pins["bb_version"] == BB_VERSION
    assert toolchain["nargo_version"] == pins["nargo_version"] == NARGO_VERSION
    assert toolchain["bb_source_revision"] == pins["bb_source_revision"]
    assert toolchain["noir_source_revision"] == pins["noir_source_revision"]
    assert toolchain["verifier_target"] == "evm"
    assert toolchain["flavor"] == "ultra_keccak_zk"
    docs = (ROOT / "docs/gitbook/smart-contract-generators/noir.md").read_text()
    assert f"Barretenberg {BB_VERSION}" in docs
    assert f"@aztec-foundation/bb.js@{BB_VERSION}" in docs


@pytest.mark.parametrize("case", MANIFEST["cases"])
def test_noir_source_and_receipt_hashes(case):
    metadata = MANIFEST["cases"][case]
    for path, expected in metadata["source_sha256"].items():
        assert hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == expected, path
    for data in metadata["files"].values():
        assert (
            hashlib.sha256((EXAMPLES / data["path"]).read_bytes()).hexdigest()
            == data["sha256"]
        )


@pytest.mark.parametrize("case", MANIFEST["cases"])
def test_noir_python_rust_and_generated_calldata(case):
    files = bundle(case)
    vk = HonkVk.from_bytes(files["vk"])
    assert vk.vk_hash == int.from_bytes(files["vk_hash"], "big")
    proof = ZKHonkProof.from_bytes(files["proof"], files["public_inputs"], vk)
    python = get_ultra_flavor_honk_calldata_from_vk_and_proof(vk, proof)
    rust = get_ultra_flavor_honk_calldata_from_vk_and_proof(vk, proof, use_rust=True)
    assert python == rust
    vectors = json.loads((EXAMPLES / "noir_calldata_test_vectors.json").read_text())
    vector = next(value for value in vectors if value["case"] == case)
    assert vector["files"] == {
        name: value.hex() for name, value in files.items() if name != "vk_hash"
    }
    assert vector["length"] == len(python)
    assert (
        vector["sha256"]
        == hashlib.sha256("\n".join(map(str, python)).encode()).hexdigest()
    )

    folder = (
        "noir_ultra_keccak_zk_honk_example"
        if case == "hello"
        else f"noir_ultra_keccak_zk_honk_{case}"
    )
    golden = ROOT / "src/contracts/autogenerated" / folder / "tests/proof_calldata.txt"
    assert [int(word, 0) for word in golden.read_text().split()] == python[1:]


@pytest.mark.parametrize(
    "word,value",
    [
        (0, 2**136),
        (1, 2**120),
        (8, CURVES[CurveID.BN254.value].p),
        (28, CURVES[CurveID.BN254.value].n),
    ],
)
def test_noir_rejects_noncanonical_proof_words(word, value):
    files = bundle("hello")
    proof = bytearray(files["proof"])
    proof[word * 32 : (word + 1) * 32] = value.to_bytes(32, "big")
    vk = HonkVk.from_bytes(files["vk"])
    with pytest.raises((AssertionError, ValueError)):
        ZKHonkProof.from_bytes(bytes(proof), files["public_inputs"], vk)
    with pytest.raises(ValueError):
        garaga_rs.get_zk_honk_calldata(
            bytes(proof), files["public_inputs"], files["vk"]
        )


def test_noir_rejects_noncanonical_public_input():
    files = bundle("hello")
    public_inputs = CURVES[CurveID.BN254.value].n.to_bytes(32, "big")
    vk = HonkVk.from_bytes(files["vk"])
    with pytest.raises(AssertionError):
        ZKHonkProof.from_bytes(files["proof"], public_inputs, vk)
    with pytest.raises(ValueError):
        garaga_rs.get_zk_honk_calldata(files["proof"], public_inputs, files["vk"])


@pytest.mark.parametrize("case", MANIFEST["cases"])
def test_key_specialization_preserves_every_relation(case):
    vk = HonkVk.from_bytes(bundle(case)["vk"])
    omitted = vk.zero_commitment_indexes()
    rng = random.Random(6000)
    modulus = CURVES[CurveID.BN254.value].n
    for _ in range(8):
        evaluations = [rng.randrange(modulus) for _ in range(41)]
        for index in omitted:
            evaluations[index] = 0
        parameters = [rng.randrange(1, modulus) for _ in range(8)]
        generic = ZKHonkVerifierCircuits("generic", vk.log_circuit_size)
        specialized = ZKHonkVerifierCircuits(
            "specialized", vk.log_circuit_size, zero_commitments=omitted
        )
        assert specialized.zero_commitments == frozenset(
            Wire(index) for index in omitted
        )
        results = []
        for circuit in (generic, specialized):
            values = circuit.accumulate_relation_evaluations(
                circuit.write_elements(evaluations),
                *circuit.write_elements(parameters),
            )
            results.append([value.value for value in values])
        assert results[0] == results[1]
        assert (
            specialized.values_segment.summarize()[1]
            < generic.values_segment.summarize()[1]
        )


@pytest.mark.parametrize(
    "coordinates", [(1, 2, 0, 0), (0, 0, 1, 2), (CURVES[0].p, 2, 1, 2)]
)
def test_noir_accumulator_rejects_mixed_infinity_and_noncanonical_coordinates(
    coordinates,
):
    from garaga.precompiled_circuits.zk_honk import decode_pairing_accumulator

    limbs = [part for value in coordinates for part in (value % 2**136, value >> 136)]
    with pytest.raises((AssertionError, ValueError)):
        decode_pairing_accumulator(limbs)


def test_mutator_set_embedded_verifier_and_receipt_match_generated_example():
    embedded = ROOT / "src/contracts/mutator_set"
    generated = (
        ROOT / "src/contracts/autogenerated/noir_ultra_keccak_zk_honk_mutator_set"
    )
    for local, reference in (
        ("honk_verifier_contract.cairo", "honk_verifier.cairo"),
        ("honk_verifier_constants.cairo", "honk_verifier_constants.cairo"),
        ("honk_verifier_circuits.cairo", "honk_verifier_circuits.cairo"),
    ):
        actual = (embedded / "src/zk_verifier" / local).read_text()
        expected = (generated / "src" / reference).read_text()
        if expected.startswith("// Generated by Garaga version "):
            expected = expected.split("\n", 1)[1]
        assert [line for line in actual.splitlines() if line.strip()] == [
            line for line in expected.splitlines() if line.strip()
        ]
    assert (embedded / "tests/proof_calldata.txt").read_bytes() == (
        generated / "tests/proof_calldata.txt"
    ).read_bytes()
