import json
import re
import tomllib
from pathlib import Path

import pytest
from garaga.starknet import constants as runtime_constants
from garaga.starknet.groth16_contract_generator.calldata import (
    groth16_calldata_from_vk_and_proof,
)
from garaga.starknet.groth16_contract_generator.parsing_utils import (
    Groth16Proof,
    Groth16VerifyingKey,
    split_digest,
)

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = json.loads((ROOT / "tools/make/constants.json").read_text())
PROVER = ROOT / "src/contracts/risc0_sample_app/fibonacci_prover"
EXAMPLES = ROOT / "hydra/garaga/starknet/groth16_contract_generator/examples"
VERIFIER = ROOT / "src/contracts/autogenerated/risc0_verifier_bn254"


@pytest.mark.parametrize(
    "manifest, section, dependency, version_key",
    [
        ("host/Cargo.toml", "dependencies", "risc0-zkvm", "risc0_zkvm_version"),
        (
            "methods/Cargo.toml",
            "build-dependencies",
            "risc0-build",
            "risc0_build_version",
        ),
        (
            "methods/guest/Cargo.toml",
            "dependencies",
            "risc0-zkvm",
            "risc0_zkvm_version",
        ),
    ],
)
def test_prover_manifests_pin_the_release(manifest, section, dependency, version_key):
    version = tomllib.loads((PROVER / manifest).read_text())[section][dependency][
        "version"
    ]
    assert (
        version == "=" + CONSTANTS["release_info"][version_key]
    ), f"{manifest} version differs from constants.json. Run make constants."


@pytest.mark.parametrize(
    "lockfile, dependency, version_key",
    [
        ("Cargo.lock", "risc0-zkvm", "risc0_zkvm_version"),
        ("Cargo.lock", "risc0-build", "risc0_build_version"),
        ("methods/guest/Cargo.lock", "risc0-zkvm", "risc0_zkvm_version"),
    ],
)
def test_resolved_sdk_matches_the_canonical_release(lockfile, dependency, version_key):
    lock = tomllib.loads((PROVER / lockfile).read_text())
    resolved = [
        package["version"]
        for package in lock["package"]
        if package["name"] == dependency
    ]
    assert resolved == [
        CONSTANTS["release_info"][version_key]
    ], f"{lockfile} resolves a different version of {dependency}."


def test_default_python_parameters_match_the_release_manifest():
    assert runtime_constants.RISC0_CONTROL_ROOT == int(
        CONSTANTS["risc0"]["control_root"], 16
    )
    assert runtime_constants.RISC0_BN254_CONTROL_ID == int(
        CONSTANTS["risc0"]["bn254_control_id"], 16
    )
    assert runtime_constants.RISC0_GROTH16_SELECTOR.hex() == CONSTANTS["risc0"][
        "groth16_selector"
    ].removeprefix("0x")
    assert (
        runtime_constants.RISC0_RELEASE_VERSION
        == CONSTANTS["release_info"]["risc0_release"]
    )


def test_cairo_verifier_commits_to_current_control_parameters():
    """Verify the generated verifier point against the canonical control parameters."""
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    low, high = split_digest(int(CONSTANTS["risc0"]["control_root"], 16))
    expected = (
        vk.ic[0]
        .add(vk.ic[1].scalar_mul(low))
        .add(vk.ic[2].scalar_mul(high))
        .add(vk.ic[5].scalar_mul(int(CONSTANTS["risc0"]["bn254_control_id"], 16)))
    )
    source = (VERIFIER / "src/groth16_verifier_constants.cairo").read_text()
    point = re.search(r"pub const T: G1Point = (.*?);", source, re.DOTALL)
    assert point is not None
    limbs = [
        int(word, 0)
        for word in re.findall(r"limb[0-3]:\s*(0x[0-9a-fA-F]+|\d+)", point[1])
    ]
    assert len(limbs) == 8
    coordinates = tuple(
        sum(limbs[offset + i] << (96 * i) for i in range(4)) for offset in (0, 4)
    )
    assert coordinates == (
        expected.x,
        expected.y,
    ), "The Cairo verifier uses stale control parameters. Run make constants and make rewrite."


@pytest.mark.parametrize(
    "proof_path", [EXAMPLES / "proof_risc0.json", PROVER / "proof.json"]
)
def test_committed_receipts_verify_with_default_parameters(proof_path):
    """Verify both committed receipts with the default Python and Rust parameters."""
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    proof = Groth16Proof.from_json(proof_path)
    python = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=False)
    rust = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=True)
    assert python == rust


def test_default_parser_rejects_an_unsupported_selector():
    receipt = json.loads((EXAMPLES / "proof_risc0.json").read_text())
    receipt["seal"] = "0x00000000" + receipt["seal"][10:]
    with pytest.raises(ValueError, match="Unsupported RISC Zero Groth16 selector"):
        Groth16Proof.from_dict(receipt)


@pytest.mark.parametrize(
    "proof_path, calldata_path",
    [
        (EXAMPLES / "proof_risc0.json", VERIFIER / "tests/proof_calldata.txt"),
        (
            PROVER / "proof.json",
            PROVER.parent / "fibonacci_sequencer/tests/proof_calldata.txt",
        ),
    ],
)
def test_committed_cairo_calldata_matches_the_receipt(proof_path, calldata_path):
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    proof = Groth16Proof.from_json(proof_path)
    expected = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=True)[1:]
    stored = [
        int(line.strip(), 0)
        for line in calldata_path.read_text().splitlines()
        if line.strip()
    ]
    assert stored == expected, "Stored Cairo calldata is stale. Run make rewrite."
