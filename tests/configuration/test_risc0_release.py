import json
import re
import tomllib
from pathlib import Path

import pytest

from garaga.starknet import constants as runtime_constants
from garaga.starknet.groth16_contract_generator.calldata import (
    groth16_calldata_from_vk_and_proof,
)
from garaga.starknet.groth16_contract_generator.parsing_utils import (
    Groth16Proof,
    Groth16VerifyingKey,
    split_digest,
)

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = json.loads((ROOT / "tools/make/constants.json").read_text())
PROVER = ROOT / "src/contracts/risc0_sample_app/fibonacci_prover"
EXAMPLES = ROOT / "hydra/garaga/starknet/groth16_contract_generator/examples"
VERIFIER = ROOT / "src/contracts/autogenerated/risc0_verifier_bn254"


@pytest.mark.parametrize(
    "manifest, section, dependency",
    [
        ("host/Cargo.toml", "dependencies", "risc0-zkvm"),
        ("methods/Cargo.toml", "build-dependencies", "risc0-build"),
        ("methods/guest/Cargo.toml", "dependencies", "risc0-zkvm"),
    ],
)
def test_sdk_and_default_verifier_use_same_release(manifest, section, dependency):
    sdk = tomllib.loads((PROVER / manifest).read_text())[section][dependency]["version"]
    verifier = CONSTANTS["release_info"]["risc0_release"].removeprefix("v")
    assert (
        sdk == CONSTANTS["release_info"]["risc0_zkvm_version"]
    ), f"{manifest} SDK version differs from constants.json. Run make constants."
    assert sdk.split(".")[0] == verifier.split(".")[0], (
        f"{manifest} uses RISC Zero {sdk}, but the default verifier uses {verifier}. "
        "Update constants.json, proofs, and generated verifier artifacts together."
    )


@pytest.mark.parametrize("lockfile", ["Cargo.lock", "methods/guest/Cargo.lock"])
def test_resolved_sdk_matches_the_canonical_release(lockfile):
    lock = tomllib.loads((PROVER / lockfile).read_text())
    resolved = next(
        package["version"]
        for package in lock["package"]
        if package["name"] == "risc0-zkvm"
    )
    assert (
        resolved == CONSTANTS["release_info"]["risc0_zkvm_version"]
    ), "A prover lockfile resolves a different SDK. Update the dependencies and regenerate its proof."


