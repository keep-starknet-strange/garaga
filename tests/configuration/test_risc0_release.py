def test_cairo_verifier_commits_to_current_control_parameters():
    """Verify the generated verifier point against the canonical control parameters."""
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    low, high = split_digest(int(CONSTANTS["risc0"]["control_root"], 16))
    expected = (
        vk.ic[0]
        .add(vk.ic[1].scalar_mul(low))
        .add(vk.ic[2].scalar_mul(high))
        .add(vk.ic[5].scalar_mul(int(CONSTANTS["risc0"]["bn254_control_id"], 16)))
    )
    source = (VERIFIER / "src/groth16_verifier_constants.cairo").read_text()
    point = re.search(r"pub const T: G1Point = (.*?);", source, re.DOTALL)
    assert point is not None
    limbs = [
        int(word, 0)
        for word in re.findall(r"limb[0-3]:\s*(0x[0-9a-fA-F]+|\d+)", point[1])
    ]
    assert len(limbs) == 8
    coordinates = tuple(
        sum(limbs[offset + i] << (96 * i) for i in range(4)) for offset in (0, 4)
    )
    assert coordinates == (
        expected.x,
        expected.y,
    ), "The Cairo verifier uses stale control parameters. Run make constants and make rewrite."


@pytest.mark.parametrize(
    "proof_path", [EXAMPLES / "proof_risc0.json", PROVER / "proof.json"]
)
def test_committed_receipts_verify_with_default_parameters(proof_path):
    """Verify both committed receipts with the default Python and Rust parameters."""
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    proof = Groth16Proof.from_json(proof_path)
    python = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=False)
    rust = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=True)
    assert python == rust


@pytest.mark.parametrize(
    "proof_path, calldata_path",
    [
        (EXAMPLES / "proof_risc0.json", VERIFIER / "tests/proof_calldata.txt"),
        (
            PROVER / "proof.json",
            PROVER.parent / "fibonacci_sequencer/tests/proof_calldata.txt",
        ),
    ],
)
def test_committed_cairo_calldata_matches_the_receipt(proof_path, calldata_path):
    vk = Groth16VerifyingKey.from_json(EXAMPLES / "vk_risc0.json")
    proof = Groth16Proof.from_json(proof_path)
    expected = groth16_calldata_from_vk_and_proof(vk, proof, use_rust=True)[1:]
    stored = [
        int(line.strip(), 0)
        for line in calldata_path.read_text().splitlines()
        if line.strip()
    ]
    assert stored == expected, "Stored Cairo calldata is stale. Run make rewrite."
